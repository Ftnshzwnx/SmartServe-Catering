export function useLocalization() {
    const t = (key) => {
        return translations[locale.value]?.[key] || translations['en']?.[key] || key;
    };

    const setLanguage = (lang) => {
        locale.value = lang;
        localStorage.setItem('ssc_locale', lang);
    };

    const currentLanguage = computed(() => locale.value);

    const translateNotification = (item) => {
        const lang = locale.value;
        const type = item.type;
        const msg = item.message || '';
        const title = item.title || '';

        let transTitle = title;
        let transMsg = msg;

        // Check if title has a " / " slash (bilingual title)
        if (title.includes(' / ')) {
            const parts = title.split(' / ');
            transTitle = lang === 'en' ? parts[1] : parts[0];
        } else {
            // Fallback title translation rules
            if (lang === 'en') {
                if (title.toLowerCase().includes('resit pembayaran dimuat naik')) {
                    transTitle = 'Payment Receipt Uploaded';
                } else if (title.toLowerCase().includes('tempahan baru')) {
                    transTitle = 'New Order';
                } else if (title.toLowerCase().includes('tempahan dibatalkan')) {
                    transTitle = 'Order Cancelled';
                } else if (title.toLowerCase().includes('cadangan menu')) {
                    transTitle = 'Menu Proposal';
                }
            }
        }

        if (lang === 'my') {
            // For Malay, clean up slash statuses like "diluluskan / approved" -> "diluluskan"
            transMsg = transMsg
                .replace(/\s*\/\s*approved/gi, '')
                .replace(/\s*\/\s*rejected/gi, '')
                .replace(/\s*\/\s*deposit/gi, '')
                .replace(/\s*\/\s*balance/gi, '')
                .replace(/\s*\/\s*baki/gi, '');
            return { title: transTitle, message: transMsg };
        }

        // English translation rules based on notification type
        switch (type) {
            case 'order_placed': {
                const match = msg.match(/Tempahan\s+#(\d+)\s+telah\s+dibuat\s+oleh\s+(.*?)\s+untuk\s+tarikh\s+([\d-]+)/i);
                if (match) {
                    transMsg = `Order #${match[1]} has been placed by ${match[2]} for date ${match[3]}.`;
                }
                break;
            }
            case 'order_cancelled': {
                const match = msg.match(/Tempahan\s+#(\d+)\s+telah\s+dibatalkan\s+oleh\s+(.*?)\./i);
                if (match) {
                    transMsg = `Order #${match[1]} has been cancelled by ${match[2]}.`;
                }
                break;
            }
            case 'payment_submitted': {
                const match = msg.match(/Resit\s+(.*?)\s+baru\s+dimuat\s+naik\s+untuk\s+tempahan\s+#(\d+)\s+oleh\s+(.*?)\./i);
                if (match) {
                    let paymentType = match[1].toLowerCase().includes('deposit') ? 'deposit' : 'balance';
                    transMsg = `New ${paymentType} receipt has been uploaded for order #${match[2]} by ${match[3]}.`;
                }
                break;
            }
            case 'proposal_approved': {
                const match = msg.match(/tempahan\s+#(\d+)/i);
                if (match) {
                    transMsg = `Custom menu proposal for order #${match[1]} has been approved by the customer.`;
                }
                break;
            }
            case 'proposal_rejected': {
                const match = msg.match(/tempahan\s+#(\d+)/i);
                if (match) {
                    transMsg = `Custom menu proposal for order #${match[1]} has been rejected by the customer.`;
                }
                break;
            }
            case 'proposal_requested': {
                const match = msg.match(/Pelanggan\s+(.*?)\s+telah\s+memohon/i);
                if (match) {
                    transMsg = `Customer ${match[1]} has requested a new custom menu proposal.`;
                }
                break;
            }
            case 'review_added': {
                const match = msg.match(/Ulasan\s+bintang\s+(\d+)\s+baru\s+diterima\s+daripada\s+(.*?)\s+untuk\s+tempahan\s+#(\d+)/i);
                if (match) {
                    transMsg = `A new ${match[1]}-star review has been received from ${match[2]} for order #${match[3]}.`;
                }
                break;
            }
            case 'payment_verified': {
                const match = msg.match(/Pembayaran\s+resit\s+anda\s+untuk\s+tempahan\s+#(\d+)\s+telah\s+(.*?)\./i);
                if (match) {
                    let status = match[2].toLowerCase().includes('lulus') || match[2].toLowerCase().includes('approve') ? 'approved' : 'rejected';
                    transMsg = `Your payment receipt for order #${match[1]} has been ${status}.`;
                }
                break;
            }
            case 'delivery_update': {
                const match = msg.match(/Tempahan\s+#(\d+)\s+anda\s+sedang/i);
                if (match) {
                    transMsg = `Your order #${match[1]} is out for delivery/setup to your location.`;
                }
                break;
            }
            case 'proposal_sent': {
                const match = msg.match(/tempahan\s+#(\d+)\s+telah/i);
                if (match) {
                    transMsg = `Custom menu proposal for order #${match[1]} has been sent. Please review and approve.`;
                }
                break;
            }
            case 'review_replied': {
                transMsg = 'Your review has been replied to by the administrator.';
                break;
            }
        }

        return { title: transTitle, message: transMsg };
    };

    return {
        t,
        setLanguage,
        currentLanguage,
        translateNotification,
    };
}
